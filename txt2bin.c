#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <fcntl.h>
#include <sys/types.h>
#include <sys/stat.h>
#ifdef WIN32
#include <io.h>
#else
#include <unistd.h>
#ifndef CYGWIN
#define O_BINARY 0
#endif
#endif

#define MAX_LINE_LEN 1024
static char line[MAX_LINE_LEN];

#define MAX_FILENAME_LEN 256
static char output_filename[MAX_FILENAME_LEN];

static char usage[] = "usage: txt2bin filename\n";
static char couldnt_open[] = "couldn't open %s\n";

static void GetLine(FILE *fptr,char *line,int *line_len,int maxllen);

int main(int argc,char **argv)
{
  FILE *fptr;
  int line_len;
  int line_no;
  int fhndl;
  int work;
  unsigned int bytes_to_write;
  unsigned int bytes_written;

  if (argc != 2) {
    printf(usage);
    return 1;
  }

  if ((fptr = fopen(argv[1],"r")) == NULL) {
    printf(couldnt_open,argv[1]);
    return 2;
  }

  sprintf(output_filename,"%s%s",argv[1],".bin");

  if ((fhndl = open(output_filename,
    O_CREAT | O_EXCL | O_BINARY | O_WRONLY,
    S_IREAD | S_IWRITE)) == -1) {
    printf(couldnt_open,output_filename);
    return 3;
  }

  bytes_to_write = sizeof(int);

  line_no = 0;

  for ( ; ; ) {
    GetLine(fptr,line,&line_len,MAX_LINE_LEN);

    if (feof(fptr))
      break;

    line_no++;

    sscanf(line,"%d",&work);

    bytes_written = write(fhndl,&work,bytes_to_write);

    if (bytes_written != bytes_to_write) {
      printf("failed to write %d bytes\n",bytes_to_write);
      close(fhndl);
      return 4;
    }
  }

  fclose(fptr);
  close(fhndl);

  return 0;
}

static void GetLine(FILE *fptr,char *line,int *line_len,int maxllen)
{
  int chara;
  int local_line_len;

  local_line_len = 0;

  for ( ; ; ) {
    chara = fgetc(fptr);

    if (feof(fptr))
      break;

    if (chara == '\n')
      break;

    if (local_line_len < maxllen - 1)
      line[local_line_len++] = (char)chara;
  }

  line[local_line_len] = 0;
  *line_len = local_line_len;
}
